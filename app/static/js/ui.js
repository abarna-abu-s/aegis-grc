export const PALETTE = { ok: '#4F7A55', warn: '#C28A2B', bad: '#A8402F', info: '#5B7A8C', neutral: '#B9A894', caramel: '#B88962', brown: '#76543F' };

export function stackedBar(parts, total) {
  const sum = total ?? (parts.reduce((a, p) => a + p.value, 0) || 1);
  return h('div', {}, h('div', { class: 'bar', role: 'img', 'aria-label': parts.map((p) => `${p.label}: ${p.value}`).join(', ') }, parts.map((p) => h('span', { style: { width: `${(100 * p.value) / sum}%`, background: p.color }, title: `${p.label}: ${p.value}` }))),
    h('div', { class: 'legend' }, parts.map((p) => h('span', {}, h('i', { style: { background: p.color } }), `${p.label} ${p.value}`))));
}

export function donut(parts, centerText, centerSub) {
  const total = parts.reduce((a, p) => a + p.value, 0);
  const r = 52, c = 2 * Math.PI * r;
  let off = 0;
  const s = svg('svg', { viewBox: '0 0 140 140', width: 150, height: 150, role: 'img', 'aria-label': parts.map((p) => `${p.label} ${p.value}`).join(', '), class: 'chart' });
  s.append(svg('circle', { cx: 70, cy: 70, r, fill: 'none', stroke: 'var(--muted-bg)', 'stroke-width': 18 }));
  if (total) parts.forEach((p) => { const len = (p.value / total) * c; s.append(svg('circle', { cx: 70, cy: 70, r, fill: 'none', stroke: p.color, 'stroke-width': 18, 'stroke-dasharray': `${len} ${c - len}`, 'stroke-dashoffset': -off, transform: 'rotate(-90 70 70)' }, svg('title', {}, `${p.label}: ${p.value}`))); off += len; });
  s.append(svg('text', { x: 70, y: 70, 'text-anchor': 'middle', 'font-size': 22, style: 'fill:var(--text);font-family:var(--serif)' }, centerText ?? total), svg('text', { x: 70, y: 88, 'text-anchor': 'middle' }, centerSub || ''));
  return h('div', { class: 'row', style: { gap: '18px' } }, s, h('div', { class: 'legend', style: { flexDirection: 'column', gap: '6px' } }, parts.map((p) => h('span', {}, h('i', { style: { background: p.color } }), `${p.label}: ${p.value}`))));
}

export function lineChart(series, { height = 180, yMax = 100 } = {}) {
  const pts = series.flatMap((s) => s.points);
  if (!pts.length) return empty('No trend data yet', 'Scores are recorded once per day while the dashboard is in use.');
  const dates = [...new Set(pts.map((p) => p.date))].sort();
  const W = 620, H = height, L = 34, B = 24, T = 8, R = 10;
  const x = (d) => L + (dates.length === 1 ? (W - L - R) / 2 : (dates.indexOf(d) / (dates.length - 1)) * (W - L - R));
  const y = (v) => T + (1 - v / yMax) * (H - T - B);
  const s = svg('svg', { viewBox: `0 0 ${W} ${H}`, class: 'chart', width: '100%', role: 'img', 'aria-label': 'Score trend' });
  [0, 25, 50, 75, 100].forEach((v) => s.append(svg('line', { x1: L, x2: W - R, y1: y(v), y2: y(v), class: 'gridline' }), svg('text', { x: L - 6, y: y(v) + 4, 'text-anchor': 'end' }, v)));
  [dates[0], dates[dates.length - 1]].forEach((d, i) => s.append(svg('text', { x: x(d), y: H - 6, 'text-anchor': i ? 'end' : 'start' }, fmtDate(d))));
  series.forEach((ser) => {
    if (ser.points.length > 1) s.append(svg('polyline', { fill: 'none', stroke: ser.color, 'stroke-width': 2.2, points: ser.points.map((p) => `${x(p.date)},${y(p.score)}`).join(' ') }));
    ser.points.forEach((p) => s.append(svg('circle', { cx: x(p.date), cy: y(p.score), r: 3.5, fill: ser.color }, svg('title', {}, `${ser.label} ${fmtDate(p.date)}: ${p.score}${p.demo_seed ? ' (demo seed)' : ''}`))));
  });
  return h('div', {}, s, h('div', { class: 'legend' }, series.map((ser) => h('span', {}, h('i', { style: { background: ser.color } }), ser.label))));
}

