// ---------------------------------------------------------------- modal / confirm / form
export function modal(title, body, { wide = false, footer } = {}) {
  const prevFocus = document.activeElement;
  const close = () => { overlay.remove(); document.removeEventListener('keydown', onKey); if (prevFocus && prevFocus.focus) prevFocus.focus(); };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  const box = h('div', { class: `modal ${wide ? 'wide' : ''}`, role: 'dialog', 'aria-modal': 'true', 'aria-label': title },
    h('div', { class: 'modal-head' }, h('h2', {}, title), h('button', { class: 'icon-btn', 'aria-label': 'Close', onClick: close }, '✕')),
    h('div', { class: 'modal-body' }, body), footer ? h('div', { class: 'modal-foot' }, footer(close)) : null);
  const overlay = h('div', { class: 'overlay', onMousedown: (e) => { if (e.target === overlay) close(); } }, box);
  document.body.append(overlay);
  document.addEventListener('keydown', onKey);
  const first = box.querySelector('input,select,textarea,button.primary');
  if (first) first.focus();
  return { close, box };
}

export function confirmDialog(message, { confirmText = 'Confirm', danger = false, title = 'Please confirm' } = {}) {
  return new Promise((resolve) => {
    let done = false;
    const finish = (v, close) => { if (!done) { done = true; resolve(v); close(); } };
    const m = modal(title, h('p', {}, message), {
      footer: (close) => [h('button', { class: 'btn', onClick: () => finish(false, close) }, 'Cancel'),
        h('button', { class: `btn ${danger ? 'danger' : 'primary'}`, onClick: () => finish(true, close) }, confirmText)],
    });
    new MutationObserver((_, o) => { if (!document.body.contains(m.box)) { if (!done) { done = true; resolve(false); } o.disconnect(); } }).observe(document.body, { childList: true });
  });
}

export function formModal({ title, fields, initial = {}, submitText = 'Save', onSubmit, wide = false, intro }) {
  const inputs = {};
  const rows = fields.map((f) => {
    const val = initial[f.name] ?? f.value ?? '';
    let input;
    if (f.type === 'textarea') input = h('textarea', { name: f.name, rows: f.rows || 4 }, val);
    else if (f.type === 'select') {
      input = h('select', { name: f.name });
      const fill = (opts) => { clear(input); (f.required ? [] : [h('option', { value: '' }, f.blank || '-- none --')]).forEach((o) => input.append(o));
        opts.forEach((o) => input.append(h('option', { value: o.value, selected: String(o.value) === String(val) }, o.label))); input.value = val === null ? '' : String(val); };
      if (typeof f.options === 'function') { fill([]); Promise.resolve(f.options()).then(fill).catch(() => {}); } else fill(f.options || []);
    } else if (f.type === 'checkbox') input = h('input', { type: 'checkbox', name: f.name, checked: !!val });
    else if (f.type === 'file') input = h('input', { type: 'file', name: f.name, accept: f.accept });
    else input = h('input', { type: f.type || 'text', name: f.name, value: val, maxlength: f.max, min: f.min, max: f.maxValue, autocomplete: f.type === 'password' ? 'new-password' : 'off' });
    inputs[f.name] = input;
    const err = h('div', { class: 'err', role: 'alert' });
    const wrap = h('label', { class: `field ${f.full ? 'full' : ''}` }, f.type === 'checkbox' ? h('span', { class: 'checkbox' }, input, f.label) : [f.label + (f.required ? ' *' : ''), input],
      f.hint ? h('div', { class: 'hint' }, f.hint) : null, err);
    wrap._err = err;
    return wrap;
  });
  const banner = h('div', { class: 'callout bad hidden', role: 'alert' });
  const form = h('form', { novalidate: true }, intro ? h('p', { class: 'muted' }, intro) : null, banner, h('div', { class: 'form-grid' }, rows));
  const submit = h('button', { class: 'btn primary', type: 'submit' }, submitText);
  const mm = modal(title, form, { wide });
  form.append(h('div', { class: 'modal-foot', style: { padding: '8px 0 0' } },
    h('button', { class: 'btn', type: 'button', onClick: mm.close }, 'Cancel'), submit));
  form.addEventListener('submit', async (ev) => {
    ev.preventDefault();
    rows.forEach((r) => { r._err.textContent = ''; r.classList.remove('invalid'); }); banner.classList.add('hidden');
    const values = {};
    const clientErrors = {};
    fields.forEach((f) => {
      const el = inputs[f.name];
      if (f.type === 'checkbox') values[f.name] = el.checked;
      else if (f.type === 'file') values[f.name] = el.files[0] || null;
      else if (f.type === 'number') values[f.name] = el.value === '' ? null : Number(el.value);
      else values[f.name] = el.value;
      if (f.required && (values[f.name] === '' || values[f.name] === null)) clientErrors[f.name] = 'This field is required';
    });
    const show = (errs) => Object.entries(errs).forEach(([k, m]) => { const i = fields.findIndex((f) => f.name === k); if (i >= 0) { rows[i]._err.textContent = m; rows[i].classList.add('invalid'); } });
    if (Object.keys(clientErrors).length) { show(clientErrors); banner.textContent = 'Please correct the highlighted fields.'; banner.classList.remove('hidden'); return; }
    submit.disabled = true; submit.textContent = 'Saving...';
    try { await onSubmit(values); mm.close(); }
    catch (e) { show(e.errors || {}); banner.textContent = errMsg(e); banner.classList.remove('hidden'); submit.disabled = false; submit.textContent = submitText; }
  });
  return mm;
}

// ---------------------------------------------------------------- tables
export function table(columns, rows, { onRow, empty: emptyEl, sort, onSort } = {}) {
  if (!rows.length) return emptyEl || empty('Nothing here yet', 'No records match.');
  const head = h('tr', {}, columns.map((c) => h('th', { class: c.sortKey ? 'sortable' : '', scope: 'col', onClick: c.sortKey && onSort ? () => onSort(c.sortKey) : null },
    c.label, sort && sort.key === c.sortKey ? (sort.desc ? ' ▾' : ' ▴') : '')));
  const body = rows.map((r) => h('tr', { class: onRow ? 'click' : '', tabindex: onRow ? 0 : null, onClick: onRow ? () => onRow(r) : null,
    onKeydown: onRow ? (e) => { if (e.key === 'Enter') onRow(r); } : null },
    columns.map((c) => h('td', { class: c.num ? 'num' : '' }, c.render ? c.render(r) : (r[c.key] ?? '-')))));
  return h('div', { class: 'table-wrap' }, h('table', {}, h('thead', {}, head), h('tbody', {}, body)));
}

// Server-paginated list with search, filters, sorting, loading/empty/error states.
export function listView({ endpoint, columns, filters = [], search = true, pageSize = 20, onRow, emptyTitle, emptyText, emptyAction, toolbar, extraParams = {}, rowActions }) {
  const state = { page: 1, q: '', sort: null, desc: false, filters: {} };
  const host = h('div', {});
  const out = h('div', {});
  let timer;
  const bar = h('div', { class: 'filters' },
    search ? h('input', { class: 'input', type: 'search', placeholder: 'Search...', 'aria-label': 'Search', onInput: (e) => { clearTimeout(timer); timer = setTimeout(() => { state.q = e.target.value; state.page = 1; load(); }, 250); } }) : null,
    filters.map((f) => h('select', { class: 'input', 'aria-label': f.label, onChange: (e) => { state.filters[f.name] = e.target.value; state.page = 1; load(); } },
      h('option', { value: '' }, `${f.label}: all`), f.options.map((o) => h('option', { value: o.value ?? o }, o.label ?? label(o))))),
    toolbar || null);
  host.append(bar, out);
  async function load() {
    clear(out).append(skeleton(5));
    try {
      const d = await api(endpoint, { params: { page: state.page, page_size: pageSize, q: state.q, sort: state.sort || undefined, desc: state.desc || undefined, ...state.filters, ...extraParams } });
      clear(out);
      const cols = rowActions ? [...columns, { label: '', render: (r) => h('div', { class: 'row', onClick: (e) => e.stopPropagation() }, rowActions(r, load)) }] : columns;
      out.append(table(cols, d.items, { onRow, sort: state.sort ? { key: state.sort, desc: state.desc } : null,
        onSort: (k) => { state.desc = state.sort === k ? !state.desc : false; state.sort = k; load(); },
        empty: state.q || Object.values(state.filters).some(Boolean) ? empty('No matching records', 'Try clearing your search or filters.') : empty(emptyTitle || 'Nothing here yet', emptyText || 'Create the first record to get started.', emptyAction) }));
      if (d.total > pageSize) {
        const pages = Math.ceil(d.total / pageSize);
        out.append(h('div', { class: 'pager' }, h('span', {}, `${(d.page - 1) * pageSize + 1}-${Math.min(d.page * pageSize, d.total)} of ${d.total}`),
          h('div', { class: 'row' }, h('button', { class: 'btn sm', disabled: d.page <= 1, onClick: () => { state.page--; load(); } }, 'Previous'),
            h('span', {}, `Page ${d.page} of ${pages}`), h('button', { class: 'btn sm', disabled: d.page >= pages, onClick: () => { state.page++; load(); } }, 'Next'))));
      }
    } catch (e) { clear(out).append(errorState(e, load)); }
  }
  host.reload = load;
  load();
  return host;
}

